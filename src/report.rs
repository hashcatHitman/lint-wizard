extern crate alloc;

use alloc::collections::btree_map::BTreeMap;
use core::fmt::{self, Display};

use cargo_util_schemas::manifest::TomlLint;

use crate::lints::LintLevel;
use crate::lints::clippy::{ClippyGroup, ConfiguredClippyLint};
use crate::lints::rustc::{ConfiguredRustcLint, RustcGroup};

#[derive(Debug, Clone)]
pub struct LintReport<'src, 'toml> {
    rustc_groups: BTreeMap<RustcGroup, &'toml TomlLint>,
    rustc_lints: Vec<ConfiguredRustcLint<'src>>,
    clippy_groups: BTreeMap<ClippyGroup, &'toml TomlLint>,
    clippy_lints: Vec<ConfiguredClippyLint<'src>>,
}

impl<'src, 'toml> LintReport<'src, 'toml> {
    pub const fn new(
        rustc_groups: BTreeMap<RustcGroup, &'toml TomlLint>,
        rustc_lints: Vec<ConfiguredRustcLint<'src>>,
        clippy_groups: BTreeMap<ClippyGroup, &'toml TomlLint>,
        clippy_lints: Vec<ConfiguredClippyLint<'src>>,
    ) -> Self {
        Self {
            rustc_groups,
            rustc_lints,
            clippy_groups,
            clippy_lints,
        }
    }
}

impl Display for LintReport<'_, '_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(f, "# This file is automatically @generated by lint-wizard.")?;
        writeln!(f, "# It is not intended for manual editing.\n")?;

        for (group, config) in &self.rustc_groups {
            writeln!(f, "[rustc.groups.{group}]")?;
            writeln!(
                f,
                "configured_level = \"{}\"",
                LintLevel::from(config.level())
            )?;
            writeln!(f, "priority = {}\n", config.priority())?;
        }

        for lint in &self.rustc_lints {
            writeln!(f, "[rustc.lints.{}]", lint.name().replace('-', "_"))?;
            if let Some(group) = lint.group() {
                writeln!(f, "group = \"{group}\"")?;
            } else {
                writeln!(f, "group = \"no group\"")?;
            }
            writeln!(f, "default_level = \"{}\"", lint.default_level())?;
            if let Some(configured_level) = lint.configured_level() {
                writeln!(f, "configured_level = \"{configured_level}\"")?;
            } else {
                writeln!(f, "configured_level = \"unset\"")?;
            }
            writeln!(f, "meaning = {:?}\n", lint.meaning())?;
        }

        for (group, config) in &self.clippy_groups {
            writeln!(f, "[clippy.groups.{group}]")?;
            writeln!(
                f,
                "configured_level = \"{}\"",
                LintLevel::from(config.level())
            )?;
            writeln!(f, "priority = {}\n", config.priority())?;
        }

        for lint in &self.clippy_lints {
            let underscore_lint_name = lint.name().replace('-', "_");
            writeln!(
                f,
                "[clippy.lints.{}]",
                underscore_lint_name
                    .strip_prefix("clippy::")
                    .unwrap_or_else(|| &underscore_lint_name)
            )?;
            writeln!(f, "primary_group = \"{}\"", lint.primary_group())?;
            writeln!(f, "is_in_clippy_all = {}", lint.is_in_clippy_all())?;
            writeln!(f, "default_level = \"{}\"", lint.default_level())?;
            if let Some(configured_level) = lint.configured_level() {
                writeln!(f, "configured_level = \"{configured_level}\"")?;
            } else {
                writeln!(f, "configured_level = \"unset\"")?;
            }
            writeln!(f, "meaning = {:?}\n", lint.meaning())?;
        }

        Ok(())
    }
}
